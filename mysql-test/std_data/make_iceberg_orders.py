# Writes mysql-test/t/iceberg_orders.inc, the Iceberg table that
# duckdb_iceberg.test reads. The test reads a table another engine wrote, with
# two snapshots; DuckDB's COPY ... (FORMAT iceberg) writes only a new table
# with one. No mysqltest variable holds this suite's path, so the table
# travels inside the include file as base64.
#
#   python3 -m venv /tmp/ice && /tmp/ice/bin/pip install 'pyiceberg[sql-sqlite,pyarrow]'
#   /tmp/ice/bin/python mysql-test/std_data/make_iceberg_orders.py
#
# The table has two snapshots: four orders, then two more.

import base64
import io
import os
import sys
import tarfile
import tempfile

import pyarrow as pa
from pyiceberg.catalog.sql import SqlCatalog

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 't', 'iceberg_orders.inc')

with tempfile.TemporaryDirectory() as tmp:
    warehouse = os.path.join(tmp, 'warehouse')
    os.makedirs(warehouse)
    catalog = SqlCatalog('demo', uri=f'sqlite:///{tmp}/catalog.db', warehouse=f'file://{warehouse}')
    catalog.create_namespace('demo')
    schema = pa.schema([('id', pa.int64()), ('region', pa.string()), ('amount', pa.float64())])
    table = catalog.create_table('demo.orders', schema=schema)
    table.append(pa.table({'id': [1, 2, 3, 4], 'region': ['east', 'west', 'east', 'north'],
                           'amount': [10.0, 20.0, 30.0, 5.0]}, schema=schema))
    table.append(pa.table({'id': [5, 6], 'region': ['west', 'east'], 'amount': [15.0, 2.5]},
                          schema=schema))

    # A fixed name for the newest metadata file, so the test does not depend
    # on the random part of the name PyIceberg gives it.
    location = table.location().removeprefix('file://')
    newest = table.metadata_location.removeprefix('file://')
    os.replace(newest, os.path.join(location, 'metadata', 'current.metadata.json'))

    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode='w:gz') as tar:
        tar.add(location, arcname='orders')
    encoded = base64.b64encode(buf.getvalue()).decode()

lines = [encoded[i:i + 76] for i in range(0, len(encoded), 76)]
with open(OUT, 'w') as f:
    f.write('# Generated by mysql-test/std_data/make_iceberg_orders.py. Do not edit.\n')
    f.write('--write_file $MYSQL_TMP_DIR/iceberg_orders.b64\n')
    f.write('\n'.join(lines) + '\n')
    f.write('EOF\n')
print(f'wrote {OUT} ({len(encoded)} base64 bytes)', file=sys.stderr)
